// Reads the request names from the installed komodo_client package and writes
// them to src/generated/api.ts, so the MCP tools only accept real API calls.
// Run again (npm run gen) after upgrading komodo_client.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const distDir = dirname(require.resolve("komodo_client"));
const src = readFileSync(join(distDir, "responses.d.ts"), "utf8");

function names(block) {
  const body = src.split(`export type ${block} = {`)[1]?.split("};")[0];
  if (!body) throw new Error(`Could not find ${block} in komodo_client/responses.d.ts`);
  return [...body.matchAll(/^\s+([A-Za-z0-9]+):/gm)].map((m) => m[1]);
}

const read = names("ReadResponses");
const write = names("WriteResponses");
const execute = names("ExecuteResponses");
const version = JSON.parse(readFileSync(join(distDir, "..", "package.json"), "utf8")).version;

const list = (xs) => `[\n${xs.map((x) => `  "${x}",`).join("\n")}\n] as const`;
const out = `// Generated by scripts/gen-api.mjs from komodo_client@${version}. Do not edit.
export const KOMODO_CLIENT_VERSION = "${version}";
export const READ_REQUESTS = ${list(read)};
export const WRITE_REQUESTS = ${list(write)};
export const EXECUTE_REQUESTS = ${list(execute)};
`;
writeFileSync(new URL("../src/generated/api.ts", import.meta.url), out);
console.log(`api.ts: ${read.length} read, ${write.length} write, ${execute.length} execute (komodo_client@${version})`);
